# ---------------------------------------------------------------- URLs and ids
def url(page_id):
    return "/docs/" if page_id == "index" else f"/docs/{page_id}/"


def resolve_docname(cur, name):
    if name.startswith("/"):
        return name[1:]
    return posixpath.normpath(posixpath.join(posixpath.dirname(cur), name))


def page_ids():
    return sorted(p.relative_to(SRC).with_suffix("").as_posix() for p in SRC.rglob("*.rst"))


def git_date(path):
    try:
        out = subprocess.run(["git", "log", "-1", "--format=%cs", "--", str(path)], cwd=ROOT, capture_output=True, text=True).stdout.strip()
        return out or TODAY
    except OSError:
        return TODAY


def raw(text):
    return nodes.raw("", text, format="html")


# ---------------------------------------------------------------- directives and roles
class Toctree(Directive):
    has_content = True
    option_spec = {k: directives.unchanged for k in ("maxdepth", "caption", "hidden", "glob", "numbered", "titlesonly", "name")}

    def run(self):
        entries = []
        for line in self.content:
            line = line.strip()
            if not line:
                continue
            m = re.match(r"^(.*?)\s*<([^>]+)>$", line)
            title, target = (m.group(1), m.group(2)) if m else (None, line)
            external = bool(re.match(r"^[a-z]+://", target))
            entries.append((title, target if external else resolve_docname(CURRENT, target), external))
        TOCS.setdefault(CURRENT, []).append({"caption": self.options.get("caption"), "entries": entries})
        if "hidden" in self.options:
            return []
        items = []
        for title, target, external in entries:
            label = title or PAGES.get(target, {}).get("title", target)
            href = target if external else url(target)
            items.append(f'<li><a href="{html.escape(href)}">{html.escape(label)}</a></li>')
        cap = self.options.get("caption")
        head = f'<p class="caption">{html.escape(cap.rstrip(":"))}</p>' if cap else ""
        return [raw(f'<div class="toctree">{head}<ul>{"".join(items)}</ul></div>')]


class SeoDirective(Directive):
    option_spec = {"title": directives.unchanged, "description": directives.unchanged, "type": directives.unchanged}

    def run(self):
        SEO[CURRENT] = {k: " ".join(v.split()) for k, v in self.options.items()}
        return []


def media_size(stem):
    with Image.open(SRC / f"{stem}.webp") as im:
        return im.size


class ImageDirective(Directive):
    """Responsive replacement for Sphinx's image directive, using the optimized media next to the sources."""
    required_arguments = 1
    option_spec = {"width": directives.unchanged, "height": directives.unchanged, "alt": directives.unchanged,
                   "align": directives.unchanged, "target": directives.unchanged, "scale": directives.unchanged,
                   "class": directives.unchanged, "name": directives.unchanged}

    def run(self):
        global IMAGE_COUNT
        raw_path = (SRC / posixpath.dirname(CURRENT) / self.arguments[0]).resolve()
        rel = raw_path.relative_to(SRC.resolve()).as_posix()
        stem = rel.rsplit(".", 1)[0]
        alt = html.escape(self.options.get("alt", ""), quote=True)
        wopt = self.options.get("width", "")
        if not (SRC / f"{stem}.webp").exists():
            print(f"WARNING: no optimized media for {rel} (page {CURRENT})")
            return []
        nw, nh = media_size(stem)
        dw = int(wopt) if wopt.isdigit() else min(nw, 736)
        dh = round(nh * dw / nw)
        MEDIA.add(f"{stem}.webp")
        loading = "eager" if IMAGE_COUNT == 0 else "lazy"
        IMAGE_COUNT += 1
        poster = f"/docs/_media/{stem}.webp"
        if (SRC / f"{stem}.mp4").exists():
            MEDIA.update({f"{stem}.mp4", f"{stem}.webm"})
            tag = (f'<video class="anim" width="{dw}" height="{dh}" autoplay muted loop playsinline preload="metadata" '
                   f'poster="{poster}" aria-label="{alt}"><source src="/docs/_media/{stem}.mp4" type="video/mp4">'
                   f'<source src="/docs/_media/{stem}.webm" type="video/webm"></video>')
        else:
            tag = f'<img src="{poster}" width="{dw}" height="{dh}" alt="{alt}" loading="{loading}" decoding="async">'
        return [raw(tag)]


class VideoDirective(Directive):
    """Inline demo video with controls. The poster defaults to the .webp with the same stem."""
    required_arguments = 1
    option_spec = {"width": directives.unchanged, "alt": directives.unchanged, "poster": directives.unchanged}

    def run(self):
        stem = (SRC / posixpath.dirname(CURRENT) / self.arguments[0]).resolve().relative_to(SRC.resolve()).as_posix().rsplit(".", 1)[0]
        poster_stem = stem
        if "poster" in self.options:
            poster_stem = (SRC / posixpath.dirname(CURRENT) / self.options["poster"]).resolve().relative_to(SRC.resolve()).as_posix().rsplit(".", 1)[0]
        nw, nh = media_size(poster_stem)
        dw = int(self.options.get("width", min(nw, 400)))
        dh = round(nh * dw / nw)
        MEDIA.update({f"{stem}.mp4", f"{stem}.webm", f"{poster_stem}.webp"})
        alt = html.escape(self.options.get("alt", ""), quote=True)
        return [raw(f'<div class="shots"><video class="demo" controls muted playsinline preload="none" width="{dw}" height="{dh}" '
                    f'poster="/docs/_media/{poster_stem}.webp" aria-label="{alt}">'
                    f'<source src="/docs/_media/{stem}.mp4" type="video/mp4"><source src="/docs/_media/{stem}.webm" type="video/webm">'
                    f'Your browser cannot play this video.</video></div>')]


class DiagramDirective(Directive):
    """Placeholder slot for a diagram the owner still has to draw. Replace it with an image directive when ready."""
    required_arguments = 1
    final_argument_whitespace = True

    def run(self):
        alt = html.escape(self.arguments[0], quote=True)
        return [raw(f'<figure class="diagram-slot" role="img" aria-label="{alt}"><!-- TODO (owner): diagram: {alt} -->'
                    f'<svg viewBox="0 0 24 24" width="28" height="28" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" '
                    f'stroke-linejoin="round" aria-hidden="true"><rect x="3" y="4" width="18" height="16" rx="3"/><circle cx="9" cy="10" r="1.6"/>'
                    f'<path d="M4 17l5-4 3 2.5 3-3 5 4.5"/></svg><figcaption>Diagram coming soon</figcaption></figure>')]


CLASSES = {Token.Comment: "tok-c1", Token.Keyword: "tok-k", Token.Operator.Word: "tok-ow", Token.Name.Builtin: "tok-nb",
           Token.Name.Function: "tok-nf", Token.Literal.Number: "tok-mf", Token.Literal.String: "tok-s"}


def highlight(code):
    out = []
    for tok, text in lex(code, PythonLexer()):
        cls = next((c for t, c in CLASSES.items() if tok in t), None)
        out.append(f'<span class="{cls}">{html.escape(text)}</span>' if cls else html.escape(text))
    return "".join(out)


class PyCodeDirective(Directive):
    has_content = True
    option_spec = {"caption": directives.unchanged}

    def run(self):
        code = "\n".join(self.content)
        cap = f'<p class="code-caption">{html.escape(self.options["caption"])}</p>' if "caption" in self.options else ""
        return [raw(f'{cap}<pre class="code" tabindex="0" aria-label="Python code example"><code>{highlight(code)}</code></pre>')]


class AppCtaDirective(Directive):
    """End-of-tutorial card. Option :next: is 'url | title'."""
    option_spec = {"next": directives.unchanged}

    def run(self):
        nxt = ""
        if "next" in self.options:
            u, t = [x.strip() for x in self.options["next"].split("|")]
            nxt = f'<a class="cta-next" href="{html.escape(u)}">Next tutorial: {html.escape(t)} &rarr;</a>'
        return [raw(f'<div class="cta-card" role="group" aria-label="Get the app"><div><p class="cta-title">Build this model in MOMDYN, free on iPhone &amp; iPad</p>'
                    f'<p class="cta-sub">Everything in this tutorial runs in the app. No license required.</p>{nxt}</div>'
                    f'<a class="store-badge" href="{APP_STORE}">{BADGE.format(w=140, h=47)}</a></div>')]


class ParamsDirective(Directive):
    """Parameter table. Rows: name | type | default | units | description. A cell of TODO is flagged for the owner."""
    has_content = True

    def run(self):
        def cell(label, text, code=False):
            text = text.strip()
            if text == "TODO":
                return f'<td data-label="{label}"><span class="todo">TODO</span></td>'
            if text in ("", "-", "—"):
                return f'<td data-label="{label}"><span class="dash">—</span></td>'
            body = html.escape(text)
            return f'<td data-label="{label}">{"<code>" + body + "</code>" if code else body}</td>'

        rows = []
        for line in self.content:
            if not line.strip():
                continue
            parts = [p.strip() for p in line.split("|", 4)]
            parts += [""] * (5 - len(parts))
            name, typ, default, units, desc = parts
            rows.append(f'<tr><th scope="row" data-label="Name"><code>{html.escape(name)}</code></th>{cell("Type", typ, True)}'
                        f'{cell("Default", default, True)}{cell("Units", units)}{cell("Description", desc)}</tr>')
        head = "".join(f"<th scope=\"col\">{h}</th>" for h in ("Name", "Type", "Default", "Units", "Description"))
        return [raw(f'<div class="table-wrap" tabindex="0" role="region" aria-label="Parameters"><table class="params"><thead><tr>{head}</tr></thead>'
                    f'<tbody>{"".join(rows)}</tbody></table></div>')]


def tex_token(tex, display):
    TEX.append((tex, display))
    return f"@@TEX{len(TEX) - 1}@@"


def math_role(name, rawtext, text, lineno, inliner, options=None, content=None):
    return [raw(f'<span class="tex">{tex_token(utils.unescape(text, True), False)}</span>')], []


class MathDirective(Directive):
    has_content = True
    optional_arguments = 1
    final_argument_whitespace = True

    def run(self):
        tex = "\n".join(self.content) if self.content else self.arguments[0]
        return [raw(f'<div class="equation" tabindex="0" role="group" aria-label="Equation">{tex_token(tex, True)}</div>')]


def ref_role(name, rawtext, text, lineno, inliner, options=None, content=None):
    m = re.match(r"^(.*?)\s*<([^>]+)>$", text, re.S)
    title, label = (m.group(1), m.group(2)) if m else (text, text)
    page = LABELS.get(label)
    if page is None:
        msg = inliner.reporter.warning(f"unknown label {label!r}", line=lineno)
        return [inliner.problematic(rawtext, rawtext, msg)], [msg]
    return [nodes.reference(rawtext, title, refuri=f"{url(page)}#{label}")], []


for _name, _cls in (("toctree", Toctree), ("seo", SeoDirective), ("image", ImageDirective), ("video", VideoDirective),
                    ("diagram", DiagramDirective), ("pycode", PyCodeDirective), ("appcta", AppCtaDirective),
                    ("params", ParamsDirective), ("math", MathDirective)):
    directives.register_directive(_name, _cls)
roles.register_local_role("ref", ref_role)
roles.register_local_role("math", math_role)

SETTINGS = {
    "report_level": 3, "halt_level": 5, "file_insertion_enabled": False, "raw_enabled": True,
    "doctitle_xform": False, "sectsubtitle_xform": False, "initial_header_level": 2, "syntax_highlight": "none",
    "smart_quotes": True, "embed_stylesheet": False, "stylesheet_path": None, "strip_comments": True,
    "input_encoding": "utf-8",
}


# ---------------------------------------------------------------- parsing one page
def parse(page_id):
    """Parse a page and return (title, doctree) with the first top-level section unwrapped into the page title."""
    global CURRENT, IMAGE_COUNT
    CURRENT, IMAGE_COUNT = page_id, 0
    TOCS[page_id] = []
    source = (SRC / f"{page_id}.rst").read_text()
    tree = core.publish_doctree(source, source_path=str(SRC / f"{page_id}.rst"), settings_overrides=SETTINGS)
    sections = [n for n in tree.children if isinstance(n, nodes.section)]
    if not sections:
        raise SystemExit(f"{page_id}: no title section")
    first = sections[0]
    title = first[0].astext()
    pos = tree.index(first)
    tree.remove(first)
    for offset, child in enumerate(list(first.children[1:])):
        tree.insert(pos + offset, child)
    return title, tree


def rewrite_links(tree, page_id):
    """Old Sphinx pages link to 'joints/revolute.html'; point those at the new page URLs."""
    for ref in tree.findall(nodes.reference):
        uri = ref.get("refuri", "")
        if not uri or re.match(r"^([a-z]+:|/|#)", uri):
            continue
        path, _, frag = uri.partition("#")
        if path.endswith(".html"):
            target = resolve_docname(page_id, path[:-5])
            if target in PAGES or (SRC / f"{target}.rst").exists():
                ref["refuri"] = url(target) + (f"#{frag}" if frag else "")


def headings(tree):
    """H2 and H3 of the page as (level, id, title)."""
    out = []
    for sec in tree.findall(nodes.section):
        depth, n = 0, sec
        while n.parent is not None and isinstance(n.parent, nodes.section):
            depth += 1
            n = n.parent
        if depth <= 1 and sec.get("ids"):
            out.append((depth + 2, sec["ids"][0], sec[0].astext()))
    return out


def howto_steps(tree):
    """Sections titled 'Step N: ...' (not marked as an alternative path) with their first paragraph."""
    steps = []
    for sec in tree.findall(nodes.section):
        title = sec[0].astext()
        if re.match(r"^Step \d+", title) and "path" not in title.lower() and sec.get("ids"):
            para = next((p.astext() for p in sec.findall(nodes.paragraph)), title)
            steps.append((sec["ids"][0], re.sub(r"^Step \d+:?\s*", "", title), " ".join(para.split())[:300]))
    return steps


def add_anchors(body):
    """Give every heading a hover link to its own id."""
    def sub(m):
        sid, lvl, inner = m.group(1), m.group(2), m.group(3)
        label = html.escape(re.sub(r"<[^>]+>", "", inner), quote=True)
        return (f'<section id="{sid}">\n<h{lvl}>{inner}<a class="anchor" href="#{sid}" aria-label="Link to section: {label}"></a></h{lvl}>')
    return re.sub(r'<section id="([^"]+)">\s*<h([2-6])>(.*?)</h\2>', sub, body, flags=re.S)


def render_body(tree):
    out = core.publish_from_doctree(tree, writer_name="html5", settings_overrides=SETTINGS, destination_path=None).decode("utf-8")
    m = re.search(r"<body>(.*)</body>", out, re.S)
    body = re.sub(r"^<main>|</main>$", "", m.group(1).strip()) if m else out
    body = add_anchors(body)
    body = body.replace("<aside ", "<div ").replace("</aside>", "</div>")       # admonitions are not page landmarks
    body = body.replace('<pre class="literal-block">', '<pre class="literal-block" tabindex="0">')  # scrollable code is keyboard reachable
    unit = r'(?:<img [^>]*>|<video class="anim".*?</video>)'
    return re.sub(rf'{unit}(?:\s*{unit})*', lambda mm: f'<div class="shots">{mm.group(0).strip()}</div>', body, flags=re.S)


def render_tex(items):
    if not items:
        return []
    res = subprocess.run(["node", str(ROOT / "scripts" / "katex_batch.js")], input=json.dumps([{"tex": t, "display": d} for t, d in items]),
                         capture_output=True, text=True, cwd=ROOT)
    if res.returncode != 0:
        raise SystemExit("KaTeX failed (run `npm install`):\n" + res.stderr)
    return json.loads(res.stdout)


# ---------------------------------------------------------------- navigation
def build_tree():
    """Navigation tree from the toctrees, starting at the index page."""
    seen = {"index"}

    def children(pid):
        out = []
        for toc in TOCS.get(pid, []):
            for title, target, external in toc["entries"]:
                if external:
                    out.append({"id": None, "title": title or target, "url": target, "ext": True, "children": []})
                elif target in PAGES and target not in seen:
                    seen.add(target)
                    out.append({"id": target, "title": title or PAGES[target]["title"], "url": url(target), "ext": False,
                                "children": children(target)})
        return out

    return children("index")


def flatten(tree, out=None):
    out = [] if out is None else out
    for n in tree:
        if not n["ext"]:
            out.append(n)
            flatten(n["children"], out)
    return out


def contains(node, pid):
    return node["id"] == pid or any(contains(c, pid) for c in node["children"])


def tree_html(tree, pid):
    items = []
    for n in tree:
        cur = ' aria-current="page"' if n["id"] == pid else ""
        a = f'<a href="{html.escape(n["url"])}"{cur}>{html.escape(n["title"])}</a>'
        if n["children"]:
            opened = " open" if contains(n, pid) else ""
            own = f'<li><a href="{html.escape(n["url"])}"{cur}>Overview</a></li>'
            inner = tree_html(n["children"], pid)
            items.append(f'<li><details{opened}><summary>{html.escape(n["title"])}</summary><ul>{own}{inner[len("<ul>"):-len("</ul>")]}</ul></details></li>')
        else:
            items.append(f"<li>{a}</li>")
    return "<ul>" + "".join(items) + "</ul>"


def ancestors(tree, pid, trail=()):
    for n in tree:
        t = trail + (n,)
        if n["id"] == pid:
            return list(t)
        found = ancestors(n["children"], pid, t)
        if found:
            return found
    return None


def toc_html(heads):
    h2 = [h for h in heads if h[0] == 2]
    if len(h2) < 2:
        return ""
    lis, i = [], 0
    for d, sid, title in heads:
        if d == 2:
            kids = []
            j = heads.index((d, sid, title)) + 1
            while j < len(heads) and heads[j][0] == 3:
                kids.append(f'<li><a href="#{heads[j][1]}">{html.escape(heads[j][2])}</a></li>')
                j += 1
            sub = f"<ul>{''.join(kids)}</ul>" if kids else ""
            lis.append(f'<li><a href="#{sid}">{html.escape(title)}</a>{sub}</li>')
    return f'<nav aria-label="On this page"><p class="toc-title">On this page</p><ul>{"".join(lis)}</ul></nav>'


# ---------------------------------------------------------------- JSON-LD
def jsonld(pid, title, desc, crumbs, kind, modified, steps):
    blocks = [{"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": i + 1, "name": t, "item": SITE + u} for i, (t, u) in enumerate(crumbs)]}]
    person = {"@type": "Person", "name": "Eliott Radcliffe", "url": "https://dc-engineer.com"}
    org = {"@type": "Organization", "name": "DCDC LLC", "url": SITE + "/"}
    if kind == "howto" and steps:
        blocks.append({"@context": "https://schema.org", "@type": "HowTo", "name": title, "description": desc, "inLanguage": "en",
                       "author": person, "publisher": org, "dateModified": modified,
                       "tool": [{"@type": "HowToTool", "name": "MOMDYN app for iPhone and iPad"}],
                       "step": [{"@type": "HowToStep", "position": i + 1, "name": n, "text": t, "url": f"{SITE}{url(pid)}#{sid}"}
                                for i, (sid, n, t) in enumerate(steps)]})
    elif kind in ("techarticle", "howto"):
        blocks.append({"@context": "https://schema.org", "@type": "TechArticle", "headline": title, "description": desc, "inLanguage": "en",
                       "author": person, "publisher": org, "dateModified": modified, "mainEntityOfPage": SITE + url(pid)})
    return "".join(f'<script type="application/ld+json">{json.dumps(b, ensure_ascii=False)}</script>\n  ' for b in blocks).rstrip()


# ---------------------------------------------------------------- build
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--redirects", help="write redirect stubs for the old momdyn.github.io site into this directory")
    ap.add_argument("--no-search", action="store_true", help="skip the Pagefind search index")
    args = ap.parse_args()

    ids = page_ids()
    for pid in ids:  # labels first, so :ref: works in any order
        for m in re.finditer(r"^\.\. _([^:\n]+):\s*$", (SRC / f"{pid}.rst").read_text(), re.M):
            LABELS[m.group(1)] = pid
    for pid in ids:  # pass 1: titles, toctrees
        title, _ = parse(pid)
        PAGES[pid] = {"title": title, "desc": "", "headings": []}
    tree_nav = build_tree()
    order = [{"id": "index", "title": PAGES["index"]["title"]}] + [{"id": n["id"], "title": n["title"]} for n in flatten(tree_nav)]
    orphans = [p for p in ids if p not in {o["id"] for o in order}]
    if orphans:
        print("NOTE: pages not in any toctree:", orphans)

    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "_static").mkdir(parents=True)
    shutil.copy(SRC / "_theme" / "docs.css", OUT / "_static" / "docs.css")
    template = string.Template((SRC / "_theme" / "page.html").read_text())

    TEX.clear()
    SEO.clear()
    rendered = {}
    for pid in ids:  # pass 2: render with KaTeX tokens
        title, tree = parse(pid)
        rewrite_links(tree, pid)
        heads = headings(tree)
        PAGES[pid]["headings"] = heads
        STEPS[pid] = howto_steps(tree)
        rendered[pid] = (title, render_body(tree), tree)
    html_tex = render_tex(TEX)

    problems = []
    for pid in ids:
        title, body, tree = rendered[pid]
        body = re.sub(r"@@TEX(\d+)@@", lambda m: html_tex[int(m.group(1))], body)
        seo = SEO.get(pid, {})
        desc = seo.get("description", "")
        if not (120 <= len(desc) <= 155):
            problems.append(f"{pid}: description is {len(desc)} characters (need 120-155)")
        if desc.endswith(("...", "…")):
            problems.append(f"{pid}: description ends with an ellipsis")
        page_title = seo.get("title") or (f"{title} documentation | MOMDYN" if pid == "index" else f"{title} | MOMDYN Docs")
        kind = seo.get("type", "article")
        PAGES[pid].update({"desc": desc, "title_tag": page_title})
        heads = PAGES[pid]["headings"]

        trail = ancestors(tree_nav, pid) or []
        crumb_items = [("Docs", "/docs/")] + [(n["title"], n["url"]) for n in trail[:-1] if not n["ext"]]
        if pid != "index":
            crumb_items.append((title, url(pid)))
        crumbs = ""
        if pid != "index":
            lis = "".join(f'<li><a href="{u}">{html.escape(t)}</a></li>' for t, u in crumb_items[:-1])
            lis += f'<li aria-current="page">{html.escape(crumb_items[-1][0])}</li>'
            crumbs = f'      <nav class="crumbs" aria-label="Breadcrumb" data-pagefind-ignore><ol>{lis}</ol></nav>'
        ld = jsonld(pid, title, desc, crumb_items, kind, git_date(SRC / f"{pid}.rst"), STEPS.get(pid))

        idx = next(i for i, o in enumerate(order) if o["id"] == pid)
        prev_o = order[idx - 1] if idx > 0 else None
        next_o = order[idx + 1] if idx + 1 < len(order) else None
        pager = ""
        if prev_o or next_o:
            p = f'<a class="prev" href="{url(prev_o["id"])}"><span>Previous</span><b>{html.escape(prev_o["title"])}</b></a>' if prev_o else ""
            n = f'<a class="next" href="{url(next_o["id"])}"><span>Next</span><b>{html.escape(next_o["title"])}</b></a>' if next_o else ""
            pager = f'      <nav class="pager" aria-label="Pages" data-pagefind-ignore>{p}{n}</nav>'

        toc = toc_html(heads)
        in_ref = pid == "mechanism" or any(a["id"] == "mechanism" for a in trail)
        in_tut = pid == "tutorials" or any(a["id"] == "tutorials" for a in trail)
        cur = ' aria-current="page"'
        katex_css = '  <link rel="stylesheet" href="/assets/katex/katex.min.css">\n' if 'class="katex' in body else ""
        og_type = "website" if pid == "index" else "article"
        html_out = template.substitute(
            year=TODAY[:4], title_tag=html.escape(page_title), og_title=html.escape(page_title), og_type=og_type,
            description=html.escape(desc, quote=True), canonical=SITE + url(pid), jsonld=ld, katex_css=katex_css, title=html.escape(title),
            cur_home=cur if pid == "index" else "", cur_tut=cur if in_tut else "", cur_ref=cur if in_ref else "",
            tree=tree_html(tree_nav, pid).replace("<ul>", '<ul class="docs-tree">', 1), breadcrumbs=crumbs, content=body, pager=pager,
            toc=toc, toc_hidden="" if toc else " hidden", toc_mobile=f'<details class="toc-mobile" data-pagefind-ignore><summary>On this page</summary>{toc}</details>' if toc else "")
        dest = OUT / ("index.html" if pid == "index" else f"{pid}/index.html")
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(html_out)

    for rel in sorted(MEDIA):
        dest = OUT / "_media" / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(SRC / rel, dest)

    # sitemap: the home page, the legal pages and every docs page
    entries = [(SITE + "/", TODAY), (SITE + "/privacy.html", git_date(ROOT / "privacy.html")), (SITE + "/terms.html", git_date(ROOT / "terms.html"))]
    entries += [(SITE + url(p), git_date(SRC / f"{p}.rst")) for p in ids]
    body = "".join(f"  <url>\n    <loc>{u}</loc>\n    <lastmod>{d}</lastmod>\n  </url>\n" for u, d in entries)
    (ROOT / "sitemap.xml").write_text('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + body + "</urlset>\n")

    if args.redirects:
        write_redirects(pathlib.Path(args.redirects), ids)
    if not args.no_search:
        res = subprocess.run(["npx", "--no-install", "pagefind", "--site", "docs"], cwd=ROOT, capture_output=True, text=True)
        print("Search index:", (res.stdout.strip().splitlines() or ["(no output)"])[-1] if res.returncode == 0 else "FAILED\n" + res.stderr[-400:])

    for p in problems:
        print("PROBLEM:", p)
    size = sum(f.stat().st_size for f in OUT.rglob("*") if f.is_file())
    print(f"Built {len(ids)} pages, {len(MEDIA)} media files, {len(html_tex)} equations, {size/1e6:.2f} MB in docs/. Sitemap: {len(entries)} URLs.")
    if problems:
        raise SystemExit(1)


def write_redirects(dest, ids):
    """Redirect stubs for the old site: html/<page>.html -> new URL. Copy into the momdyn.github.io repo."""
    stub = string.Template('<!doctype html>\n<html lang="en">\n<meta charset="utf-8">\n<title>Moved: $title</title>\n'
                           '<link rel="canonical" href="$new">\n<meta http-equiv="refresh" content="0; url=$new">\n'
                           '<p>This page has moved to <a href="$new">$new</a>.</p>\n</html>\n')
    mapping = {f"html/{p}.html": SITE + url(p) for p in ids}
    mapping["html/genindex.html"] = SITE + "/docs/"
    mapping["html/search.html"] = SITE + "/docs/"
    mapping["index.html"] = SITE + "/docs/"
    for old, new in mapping.items():
        f = dest / old
        f.parent.mkdir(parents=True, exist_ok=True)
        title = PAGES.get(old[5:-5], {}).get("title", "MOMDYN documentation")
        f.write_text(stub.substitute(title=html.escape(title), new=new))
    (dest / "redirect-map.json").write_text(json.dumps(mapping, indent=1))
    print(f"Wrote {len(mapping)} redirect stubs to {dest}")


