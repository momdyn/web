#!/usr/bin/env python3
"""Build the documentation site: docs-src/**/*.rst  ->  docs/**/index.html (+ sitemap.xml, search index).

Usage:
    python3 scripts/build_docs.py                    # build docs/, update sitemap.xml, build the Pagefind search index
    python3 scripts/build_docs.py --no-search        # skip the search index
    python3 scripts/build_docs.py --redirects DIR    # also write redirect stubs for the OLD site (momdyn.github.io)

Inputs
  docs-src/*.rst          hand-written pages (ported from the old Sphinx site)
  docs-src/<group>/*.rst  reference pages generated by scripts/gen_reference.py (do not edit by hand)
  docs-src/**/*.webp|mp4  optimized media made by scripts/port_docs_media.py
  docs-src/_theme/        page.html (template) and docs.css

Navigation comes from the `.. toctree::` directives, like Sphinx. Extra directives and roles:
  .. seo::            per-page <title>, meta description, JSON-LD type (article | techarticle | howto)
  :math: / .. math::  LaTeX, pre-rendered with KaTeX at build time (no JavaScript on the page)
  .. params::         reference parameter table (rows: name | type | default | units | description)
  .. diagram::        placeholder slot for a diagram that is still to be drawn
  .. video::          inline <video> with controls and a poster
  .. pycode::         syntax-highlighted Python excerpt
  .. appcta::         end-of-tutorial "Build this in MOMDYN" card

Needs: pip install docutils pillow pygments;  npm install (KaTeX and Pagefind, see package.json)
"""
